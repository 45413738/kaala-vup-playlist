/**
 * 載入並正規化 songs.json
 */
async function loadSongs() {
  try {
    const res = await fetch("songs.json");
    if (!res.ok) {
      throw new Error(`HTTP 錯誤狀態碼：${res.status}`);
    }
    const rawData = await res.json();
    if (!Array.isArray(rawData)) {
      throw new Error("歌單資料格式錯誤（非陣列）");
    }

    // 清洗資料並預先建立繁簡正規化搜尋索引
    songs = rawData
      .filter(item => item && typeof item.title === "string" && item.title.trim() !== "")
      .map(item => {
        const title = item.title.trim();
        const artist = typeof item.artist === "string" ? item.artist.trim() : "";
        const genres = Array.isArray(item.genres)
          ? item.genres
              .filter(g => typeof g === "string" && g.trim() !== "")
              .map(g => g.trim())
          : [];

        const searchSource = `${title} ${artist} ${genres.join(" ")}`;
        return {
          title,
          artist,
          genres,
          _searchIndex: normalizeSearchText(searchSource)
        };
      });

    loadingMessage.style.display = "none";
    renderTags();
    renderSongs();
  } catch (err) {
    console.error("載入 songs.json 失敗：", err);
    loadingMessage.textContent = "歌單載入失敗，請重新整理頁面再試。";
  }
}

/**
 * 動態產生曲風分類標籤（自動過濾空字串）
 */
function renderTags() {
  const genresSet = new Set();
  songs.forEach(song => {
    song.genres.forEach(g => genresSet.add(g));
  });

  const uniqueGenres = Array.from(genresSet);
  tagListEl.textContent = "";

  const fragment = document.createDocumentFragment();

  const allBtn = document.createElement("button");
  allBtn.type = "button";
  allBtn.className = "tag-btn active";
  allBtn.dataset.genre = "all";
  allBtn.textContent = "全部";
  fragment.appendChild(allBtn);

  uniqueGenres.forEach(genre => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "tag-btn";
    btn.dataset.genre = genre;
    btn.textContent = genre;
    fragment.appendChild(btn);
  });

  tagListEl.appendChild(fragment);
}

