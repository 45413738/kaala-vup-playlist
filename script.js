/**
 * 將繁體中文字串轉換為簡體中文（保留英文大小寫）
 * @param {string} text
 * @returns {string}
 */
function toSimplified(text) {
  if (!text || typeof text !== "string") return "";
  let result = "";
  for (const ch of text.trim()) {
    result += tradToSimpMap.get(ch) || ch;
  }
  return result;
}

/**
 * 將字串正規化為小寫簡體，支援繁簡互通搜尋
 * @param {string} text
 * @returns {string}
 */
function normalizeSearchText(text) {
  return toSimplified(text).toLowerCase();
}

